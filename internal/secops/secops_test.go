func TestParseListeningPorts(t *testing.T) {
	output := `
  Proto  Local Address          Foreign Address        State           PID
  TCP    0.0.0.0:135            0.0.0.0:0              LISTENING       1234
  TCP    0.0.0.0:443            0.0.0.0:0              LISTENING       5678
  TCP    192.168.1.1:52411      93.184.216.34:443      ESTABLISHED     9012
  UDP    0.0.0.0:1900           *:*                                    3456
  TCP    [::]:445               [::]:0                 LISTENING       7890
`
	ports := parseListeningPorts(output)
	// Expect: 135(TCP), 443(TCP), 1900(UDP), 445(TCP-v6)
	// 52411 is ESTABLISHED, not LISTENING, so excluded
	if len(ports) != 4 {
		t.Fatalf("got %d listening ports, want 4", len(ports))
	}

	portMap := make(map[int]string)
	for _, p := range ports {
		portMap[p.Port] = p.Protocol
	}

	expected := map[int]string{135: "TCP", 443: "TCP", 1900: "UDP", 445: "TCP"}
	for port, proto := range expected {
		if p, ok := portMap[port]; !ok {
			t.Errorf("port %d not found in parsed ports", port)
		} else if p != proto {
			t.Errorf("port %d protocol = %q, want %q", port, p, proto)
		}
	}
}

