func TestParseFirewallRules_Standard(t *testing.T) {
	output := `Rule Name:                            Block TCP 3389
----------------------------------------------------------------------
Enabled:                              Yes
Direction:                            In
Profiles:                             Domain
LocalIP:                              Any
RemoteIP:                             Any
Protocol:                             TCP
LocalPort:                            3389
RemotePort:                           Any
Action:                               Block

Rule Name:                            Allow HTTP 80
----------------------------------------------------------------------
Enabled:                              Yes
Direction:                            In
Profiles:                             Public
Protocol:                             TCP
LocalPort:                            80
Action:                               Allow

Rule Name:                            Disabled Rule
----------------------------------------------------------------------
Enabled:                              No
Direction:                            Out
Protocol:                             Any
Action:                               Block
`
	rules, err := parseFirewallRules(output)
	if err != nil {
		t.Fatalf("parseFirewallRules returned error: %v", err)
	}
	if len(rules) != 3 {
		t.Fatalf("got %d rules, want 3", len(rules))
	}

	// First rule
	if rules[0].Name != "Block TCP 3389" {
		t.Errorf("rules[0].Name = %q, want %q", rules[0].Name, "Block TCP 3389")
	}
	if !rules[0].Enabled {
		t.Error("rules[0].Enabled = false, want true")
	}
	if rules[0].Direction != "In" {
		t.Errorf("rules[0].Direction = %q, want %q", rules[0].Direction, "In")
	}
	if rules[0].Protocol != "TCP" {
		t.Errorf("rules[0].Protocol = %q, want %q", rules[0].Protocol, "TCP")
	}
	if rules[0].LocalPort != "3389" {
		t.Errorf("rules[0].LocalPort = %q, want %q", rules[0].LocalPort, "3389")
	}
	if rules[0].Action != "Block" {
		t.Errorf("rules[0].Action = %q, want %q", rules[0].Action, "Block")
	}

	// Third rule (disabled)
	if rules[2].Enabled {
		t.Error("rules[2].Enabled = true, want false")
	}
	if rules[2].Action != "Block" {
		t.Errorf("rules[2].Action = %q, want %q", rules[2].Action, "Block")
	}
}

